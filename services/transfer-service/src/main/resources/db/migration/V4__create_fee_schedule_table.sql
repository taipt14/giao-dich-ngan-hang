CREATE SEQUENCE SEQ_FEE_SCHEDULE START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE TABLE FEE_SCHEDULE (
    FEE_SCHEDULE_ID NUMBER(19)    NOT NULL,
    TRANSFER_TYPE   VARCHAR2(20)  NOT NULL,
    MIN_AMOUNT      NUMBER(19, 2) NOT NULL,
    MAX_AMOUNT      NUMBER(19, 2),
    FEE_RATE        NUMBER(9, 6)  NOT NULL,
    MIN_FEE         NUMBER(19, 2) NOT NULL,
    MAX_FEE         NUMBER(19, 2) NOT NULL,
    EFFECTIVE_FROM  DATE          NOT NULL,
    VERSION         NUMBER(19)    NOT NULL,
    CONSTRAINT PK_FEE_SCHEDULE PRIMARY KEY (FEE_SCHEDULE_ID),
    -- Mot bieu phi (loai giao dich + ngay hieu luc) khong co hai khoang bat dau cung muc tien
    CONSTRAINT UK_FEE_SCHEDULE_TYPE_EFFECTIVE_MIN UNIQUE (TRANSFER_TYPE, EFFECTIVE_FROM, MIN_AMOUNT),
    CONSTRAINT CK_FEE_SCHEDULE_TRANSFER_TYPE CHECK (TRANSFER_TYPE IN ('INTERNAL', 'INTERBANK')),
    CONSTRAINT CK_FEE_SCHEDULE_MIN_AMOUNT CHECK (MIN_AMOUNT >= 0),
    CONSTRAINT CK_FEE_SCHEDULE_MAX_AMOUNT CHECK (MAX_AMOUNT IS NULL OR MAX_AMOUNT > MIN_AMOUNT),
    CONSTRAINT CK_FEE_SCHEDULE_FEE_RATE CHECK (FEE_RATE >= 0 AND FEE_RATE <= 1),
    CONSTRAINT CK_FEE_SCHEDULE_MIN_FEE CHECK (MIN_FEE >= 0),
    CONSTRAINT CK_FEE_SCHEDULE_MAX_FEE CHECK (MAX_FEE >= MIN_FEE)
);

COMMENT ON TABLE FEE_SCHEDULE IS 'Bieu phi chuyen khoan (BANK-044) theo loai giao dich va khoang so tien, co ngay hieu luc; phi da gom VAT';
COMMENT ON COLUMN FEE_SCHEDULE.FEE_SCHEDULE_ID IS 'Khoa chinh, lay tu SEQ_FEE_SCHEDULE';
COMMENT ON COLUMN FEE_SCHEDULE.TRANSFER_TYPE IS 'Loai giao dich: INTERNAL, INTERBANK';
COMMENT ON COLUMN FEE_SCHEDULE.MIN_AMOUNT IS 'Can duoi cua khoang so tien (gom ca muc nay)';
COMMENT ON COLUMN FEE_SCHEDULE.MAX_AMOUNT IS 'Can tren cua khoang so tien (khong gom muc nay), NULL la khong gioi han';
COMMENT ON COLUMN FEE_SCHEDULE.FEE_RATE IS 'Ty le phi tren so tien, vi du 0.0002 = 0,02%';
COMMENT ON COLUMN FEE_SCHEDULE.MIN_FEE IS 'Phi toi thieu (dong)';
COMMENT ON COLUMN FEE_SCHEDULE.MAX_FEE IS 'Phi toi da (dong)';
COMMENT ON COLUMN FEE_SCHEDULE.EFFECTIVE_FROM IS 'Ngay nghiep vu (gio Asia/Ho_Chi_Minh) bieu phi bat dau ap dung; cac dong cung loai va cung ngay tao thanh mot bieu phi';
COMMENT ON COLUMN FEE_SCHEDULE.VERSION IS 'Phien ban cho optimistic lock';

