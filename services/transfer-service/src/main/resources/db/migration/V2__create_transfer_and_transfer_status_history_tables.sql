CREATE SEQUENCE SEQ_TRANSFER_STATUS_HISTORY START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE TABLE TRANSFER_STATUS_HISTORY (
    TRANSFER_STATUS_HISTORY_ID NUMBER(19)   NOT NULL,
    TRANSFER_ID                VARCHAR2(36) NOT NULL,
    -- NULL o dong dau tien: lenh vua tao o trang thai INITIATED
    PREVIOUS_STATUS            VARCHAR2(20),
    STATUS                     VARCHAR2(20) NOT NULL,
    FAILURE_CODE               VARCHAR2(50),
    CHANGED_AT                 TIMESTAMP    NOT NULL,
    VERSION                    NUMBER(19)   NOT NULL,
    CONSTRAINT PK_TRANSFER_STATUS_HISTORY PRIMARY KEY (TRANSFER_STATUS_HISTORY_ID),
    CONSTRAINT FK_TRANSFER_STATUS_HISTORY_TRANSFER_ID FOREIGN KEY (TRANSFER_ID) REFERENCES TRANSFER (TRANSFER_ID),
    CONSTRAINT CK_TRANSFER_STATUS_HISTORY_PREVIOUS_STATUS CHECK (PREVIOUS_STATUS IN (
        'INITIATED', 'OTP_PENDING', 'PROCESSING', 'PENDING_NAPAS', 'SUCCESS', 'FAILED', 'REVERSED', 'UNKNOWN')),
    CONSTRAINT CK_TRANSFER_STATUS_HISTORY_STATUS CHECK (STATUS IN (
        'INITIATED', 'OTP_PENDING', 'PROCESSING', 'PENDING_NAPAS', 'SUCCESS', 'FAILED', 'REVERSED', 'UNKNOWN'))
);

-- Doc lich su theo lenh (BANK-047); Oracle khong tu tao index cho FK
CREATE INDEX IX_TRANSFER_STATUS_HISTORY_TRANSFER_ID
    ON TRANSFER_STATUS_HISTORY (TRANSFER_ID, TRANSFER_STATUS_HISTORY_ID);

COMMENT ON TABLE TRANSFER_STATUS_HISTORY IS 'Lich su doi trang thai lenh chuyen khoan, chi them moi';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.TRANSFER_STATUS_HISTORY_ID IS 'Khoa chinh, lay tu SEQ_TRANSFER_STATUS_HISTORY';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.TRANSFER_ID IS 'Ma lenh chuyen khoan';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.PREVIOUS_STATUS IS 'Trang thai truoc khi doi, NULL khi lenh vua tao';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.STATUS IS 'Trang thai sau khi doi';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.FAILURE_CODE IS 'Ma loi khi chuyen sang FAILED';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.CHANGED_AT IS 'Thoi diem doi trang thai (UTC)';
COMMENT ON COLUMN TRANSFER_STATUS_HISTORY.VERSION IS 'Phien ban cho optimistic lock';
