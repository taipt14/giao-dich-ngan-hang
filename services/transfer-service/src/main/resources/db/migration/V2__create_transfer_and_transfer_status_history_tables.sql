CREATE TABLE TRANSFER (
    -- UUID dang chuoi: dung lam key Kafka, key Redis otp:{transferId} va referenceId khi posting (toi da 64)
    TRANSFER_ID     VARCHAR2(36)       NOT NULL,
    TYPE            VARCHAR2(20)       NOT NULL,
    SOURCE_ACCOUNT  VARCHAR2(20)       NOT NULL,
    DEST_ACCOUNT    VARCHAR2(20)       NOT NULL,
    DEST_BANK_CODE  VARCHAR2(10),
    AMOUNT          NUMBER(19, 2)      NOT NULL,
    FEE             NUMBER(19, 2)      NOT NULL,
    DESCRIPTION     VARCHAR2(210 CHAR),
    STATUS          VARCHAR2(20)       NOT NULL,
    FAILURE_CODE    VARCHAR2(50),
    CIF             VARCHAR2(10)       NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(36)       NOT NULL,
    VERSION         NUMBER(19)         NOT NULL,
    CREATED_AT      TIMESTAMP          NOT NULL,
    UPDATED_AT      TIMESTAMP          NOT NULL,
    CONSTRAINT PK_TRANSFER PRIMARY KEY (TRANSFER_ID),
    -- Lop idempotency thu hai cua BANK-041 (lop dau la Redis SET NX)
    CONSTRAINT UK_TRANSFER_CIF_IDEM_KEY UNIQUE (CIF, IDEMPOTENCY_KEY),
    CONSTRAINT CK_TRANSFER_TYPE CHECK (TYPE IN ('INTERNAL', 'INTERBANK')),
    CONSTRAINT CK_TRANSFER_STATUS CHECK (STATUS IN (
        'INITIATED', 'OTP_PENDING', 'PROCESSING', 'PENDING_NAPAS', 'SUCCESS', 'FAILED', 'REVERSED', 'UNKNOWN')),
    CONSTRAINT CK_TRANSFER_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_TRANSFER_FEE CHECK (FEE >= 0),
    -- Noi bo khong co ma ngan hang dich, lien ngan hang bat buoc co
    CONSTRAINT CK_TRANSFER_DEST_BANK_CODE CHECK (
        (TYPE = 'INTERNAL' AND DEST_BANK_CODE IS NULL) OR (TYPE = 'INTERBANK' AND DEST_BANK_CODE IS NOT NULL)),
    CONSTRAINT CK_TRANSFER_FAILURE_CODE CHECK (STATUS <> 'FAILED' OR FAILURE_CODE IS NOT NULL)
);

COMMENT ON TABLE TRANSFER IS 'Lenh chuyen khoan noi bo va lien ngan hang, so do trang thai: docs/transfer-state.md';
COMMENT ON COLUMN TRANSFER.TRANSFER_ID IS 'Ma lenh chuyen khoan (UUID)';
COMMENT ON COLUMN TRANSFER.TYPE IS 'Loai lenh: INTERNAL (noi bo), INTERBANK (lien ngan hang qua NAPAS)';
COMMENT ON COLUMN TRANSFER.SOURCE_ACCOUNT IS 'So tai khoan nguon (account-service)';
COMMENT ON COLUMN TRANSFER.DEST_ACCOUNT IS 'So tai khoan dich';
COMMENT ON COLUMN TRANSFER.DEST_BANK_CODE IS 'Ma ngan hang dich, NULL voi lenh noi bo';
COMMENT ON COLUMN TRANSFER.AMOUNT IS 'So tien chuyen, luon duong';
COMMENT ON COLUMN TRANSFER.FEE IS 'Phi giao dich tinh luc tao lenh';
COMMENT ON COLUMN TRANSFER.DESCRIPTION IS 'Noi dung chuyen khoan';
COMMENT ON COLUMN TRANSFER.STATUS IS 'Trang thai: INITIATED, OTP_PENDING, PROCESSING, PENDING_NAPAS, SUCCESS, FAILED, REVERSED, UNKNOWN';
COMMENT ON COLUMN TRANSFER.FAILURE_CODE IS 'Ma loi khi lenh FAILED (vi du INSUFFICIENT_BALANCE, OTP_MAX_ATTEMPTS)';
COMMENT ON COLUMN TRANSFER.CIF IS 'Ma khach hang tao lenh';
