COMMENT ON COLUMN TRANSFER_LIMIT_CONFIG.PER_TRANSACTION_LIMIT IS 'So tien toi da moi lenh (khong gom phi)';
COMMENT ON COLUMN TRANSFER_LIMIT_CONFIG.DAILY_LIMIT IS 'Tong so tien toi da moi ngay cua mot tai khoan nguon (khong gom phi)';
COMMENT ON COLUMN TRANSFER_LIMIT_CONFIG.VERSION IS 'Phien ban cho optimistic lock';

