CREATE TABLE TRANSFER_LIMIT_CONFIG (
    CUSTOMER_TYPE         VARCHAR2(20)  NOT NULL,
    PER_TRANSACTION_LIMIT NUMBER(19, 2) NOT NULL,
    DAILY_LIMIT           NUMBER(19, 2) NOT NULL,
    VERSION               NUMBER(19)    NOT NULL,
    CONSTRAINT PK_TRANSFER_LIMIT_CONFIG PRIMARY KEY (CUSTOMER_TYPE),
    CONSTRAINT CK_TRANSFER_LIMIT_CONFIG_PER_TRANSACTION_LIMIT CHECK (PER_TRANSACTION_LIMIT > 0),
    CONSTRAINT CK_TRANSFER_LIMIT_CONFIG_DAILY_LIMIT CHECK (DAILY_LIMIT >= PER_TRANSACTION_LIMIT)
);

