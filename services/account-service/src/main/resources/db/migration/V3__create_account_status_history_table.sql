CREATE SEQUENCE SEQ_ACCOUNT_STATUS_HISTORY START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE TABLE ACCOUNT_STATUS_HISTORY (
    ACCOUNT_STATUS_HISTORY_ID NUMBER(19)         NOT NULL,
    ACCOUNT_NO                VARCHAR2(20)       NOT NULL,
    PREVIOUS_STATUS           VARCHAR2(20)       NOT NULL,
    STATUS                    VARCHAR2(20)       NOT NULL,
    -- 300 CHAR: ly do tu API toi da 255 ky tu, ly do tu dong (khach hang bi khoa) co them tien to
    REASON                    VARCHAR2(300 CHAR) NOT NULL,
    CHANGED_AT                TIMESTAMP          NOT NULL,
    VERSION                   NUMBER(19)         NOT NULL,
    CONSTRAINT PK_ACCOUNT_STATUS_HISTORY PRIMARY KEY (ACCOUNT_STATUS_HISTORY_ID),
    CONSTRAINT FK_ACCOUNT_STATUS_HISTORY_ACCOUNT_NO FOREIGN KEY (ACCOUNT_NO) REFERENCES ACCOUNT (ACCOUNT_NO),
    CONSTRAINT CK_ACCOUNT_STATUS_HISTORY_PREVIOUS_STATUS CHECK (PREVIOUS_STATUS IN ('ACTIVE', 'LOCKED', 'CLOSED')),
    CONSTRAINT CK_ACCOUNT_STATUS_HISTORY_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'CLOSED'))
);

-- Xem lich su theo tai khoan; Oracle khong tu tao index cho FK
CREATE INDEX IX_ACCOUNT_STATUS_HISTORY_ACCOUNT_NO ON ACCOUNT_STATUS_HISTORY (ACCOUNT_NO, CHANGED_AT);

COMMENT ON TABLE ACCOUNT_STATUS_HISTORY IS 'Lich su doi trang thai tai khoan';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.ACCOUNT_STATUS_HISTORY_ID IS 'Khoa chinh, lay tu SEQ_ACCOUNT_STATUS_HISTORY';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.ACCOUNT_NO IS 'So tai khoan doi trang thai';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.PREVIOUS_STATUS IS 'Trang thai truoc khi doi';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.STATUS IS 'Trang thai sau khi doi';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.REASON IS 'Ly do doi trang thai';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.CHANGED_AT IS 'Thoi diem doi trang thai (UTC)';
COMMENT ON COLUMN ACCOUNT_STATUS_HISTORY.VERSION IS 'Phien ban cho optimistic lock';
